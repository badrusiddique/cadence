const ratioCheck =
  (maxRatioKey = 'maxRatio', minSampleKey = 'minSample') =>
  (stats: { count: number; total: number; ratio: number }, th: Record<string, number>) =>
    stats.ratio > (th[maxRatioKey] ?? 0.25) && stats.count > (th[minSampleKey] ?? 5);

